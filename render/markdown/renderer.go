// Package markdown provides Markdown rendering for evaluation reports.
package markdown

import (
	"fmt"
	"io"
	"strings"

	"github.com/plexusone/structured-evaluation/rubric"
)

// Renderer renders evaluation reports as Markdown.
type Renderer struct {
	w io.Writer
}

// New creates a new Markdown renderer.
func New(w io.Writer) *Renderer {
	return &Renderer{w: w}
}

// Render outputs the evaluation report as Markdown.
func (r *Renderer) Render(report *rubric.Rubric) error {
	var b strings.Builder

	// Title
	b.WriteString("## Evaluation Report")
	if report.Metadata.DocumentTitle != "" {
		b.WriteString(": " + report.Metadata.DocumentTitle)
	}
	b.WriteString("\n\n")

	// Summary section
	b.WriteString("### Summary\n\n")
	b.WriteString(fmt.Sprintf("**Overall Decision: %s** %s\n\n",
		strings.ToUpper(string(report.Decision.Status)),
		decisionIcon(report.Decision.Status)))

	// Summary table
	catCounts := report.Decision.CategoryCounts
	findCounts := report.Decision.FindingCounts

	b.WriteString("| Metric | Value |\n")
	b.WriteString("|--------|-------|\n")
	b.WriteString(fmt.Sprintf("| Categories | %d pass, %d partial, %d fail |\n",
		catCounts.Pass, catCounts.Partial, catCounts.Fail))
	b.WriteString(fmt.Sprintf("| Findings | %d critical, %d high, %d medium |\n",
		findCounts.Critical, findCounts.High, findCounts.Medium))
	b.WriteString(fmt.Sprintf("| Decision | %s |\n", strings.Title(string(report.Decision.Status))))
	b.WriteString("\n---\n\n")

	// Metadata
	b.WriteString("### Metadata\n\n")
	b.WriteString(fmt.Sprintf("- **Document**: %s\n", report.Metadata.Document))
	if report.Metadata.DocumentTitle != "" {
		b.WriteString(fmt.Sprintf("- **Title**: %s\n", report.Metadata.DocumentTitle))
	}
	if report.RubricID != "" {
		b.WriteString(fmt.Sprintf("- **Rubric**: %s", report.RubricID))
		if report.RubricVersion != "" {
			b.WriteString(fmt.Sprintf(" v%s", report.RubricVersion))
		}
		b.WriteString("\n")
	}
	b.WriteString(fmt.Sprintf("- **Review Type**: %s\n", report.ReviewType))
	b.WriteString(fmt.Sprintf("- **Generated**: %s\n", report.Metadata.GeneratedAt.Format("2006-01-02 15:04:05 UTC")))
	b.WriteString("\n---\n\n")

	// Category Results
	b.WriteString("### Category Results\n\n")
	b.WriteString("| Category | Score | Weight | Required | Reasoning |\n")
	b.WriteString("|----------|-------|--------|----------|----------|\n")

	for _, cr := range report.Categories {
		required := ""
		// Note: We don't have required info in CategoryResult, would need rubric
		scoreStr := formatScore(cr)
		b.WriteString(fmt.Sprintf("| **%s** | %s | - | %s | %s |\n",
			cr.Category,
			scoreStr,
			required,
			truncate(cr.Reasoning, 60)))
	}
	b.WriteString("\n---\n\n")

	// Evidence section
	hasEvidence := false
	for _, cr := range report.Categories {
		if len(cr.Evidence) > 0 {
			hasEvidence = true
			break
		}
	}

	if hasEvidence {
		b.WriteString("### Evidence\n\n")
		for _, cr := range report.Categories {
			if len(cr.Evidence) > 0 {
				b.WriteString(fmt.Sprintf("**%s:**\n", cr.Category))
				for _, ev := range cr.Evidence {
					b.WriteString(fmt.Sprintf("- `%s`\n", ev))
				}
				b.WriteString("\n")
			}
		}
		b.WriteString("---\n\n")
	}

	// Findings section
	if len(report.Findings) > 0 {
		b.WriteString("### Findings\n\n")

		// Group by severity
		for _, sev := range rubric.AllSeverities() {
			findings := filterBySeverity(report.Findings, sev)
			if len(findings) == 0 {
				continue
			}

			b.WriteString(fmt.Sprintf("#### %s %s (%d)\n\n",
				severityIcon(sev),
				strings.Title(string(sev)),
				len(findings)))

			for _, f := range findings {
				b.WriteString(fmt.Sprintf("**%s** [%s]\n", f.Title, f.Category))
				b.WriteString(fmt.Sprintf("- %s\n", f.Description))
				if f.Recommendation != "" {
					b.WriteString(fmt.Sprintf("- **Recommendation**: %s\n", f.Recommendation))
				}
				b.WriteString("\n")
			}
		}
		b.WriteString("---\n\n")
	} else {
		b.WriteString("### Findings\n\n")
		b.WriteString("**None** - No issues identified.\n\n")
		b.WriteString("---\n\n")
	}

	// Next Steps
	writeNextSteps(&b, report)

	// Footer
	b.WriteString("---\n\n")
	b.WriteString("*Generated by structured-evaluation*\n")

	_, err := fmt.Fprint(r.w, b.String())
	return err
}

// RenderWithRubric renders with additional rubric context (weights, required flags).
func (r *Renderer) RenderWithRubric(report *rubric.Rubric, rubricSet *rubric.RubricSet) error {
	var b strings.Builder

	// Title
	b.WriteString("## Evaluation Report")
	if report.Metadata.DocumentTitle != "" {
		b.WriteString(": " + report.Metadata.DocumentTitle)
	}
	b.WriteString("\n\n")

	// Summary section
	b.WriteString("### Summary\n\n")
	b.WriteString(fmt.Sprintf("**Overall Decision: %s** %s\n\n",
		strings.ToUpper(string(report.Decision.Status)),
		decisionIcon(report.Decision.Status)))

	// Summary table
	catCounts := report.Decision.CategoryCounts
	findCounts := report.Decision.FindingCounts

	b.WriteString("| Metric | Value |\n")
	b.WriteString("|--------|-------|\n")
	b.WriteString(fmt.Sprintf("| Categories | %d pass, %d partial, %d fail |\n",
		catCounts.Pass, catCounts.Partial, catCounts.Fail))
	b.WriteString(fmt.Sprintf("| Findings | %d critical, %d high, %d medium |\n",
		findCounts.Critical, findCounts.High, findCounts.Medium))
	b.WriteString(fmt.Sprintf("| Decision | %s |\n", strings.Title(string(report.Decision.Status))))
	b.WriteString("\n---\n\n")

	// Category Results with rubric info
	b.WriteString("### Category Results\n\n")
	b.WriteString("| Category | Score | Weight | Required | Reasoning |\n")
	b.WriteString("|----------|-------|--------|----------|----------|\n")

	for _, cr := range report.Categories {
		weight := "-"
		required := ""

		// Look up rubric info
		if rubricSet != nil {
			if cat := rubricSet.GetCategory(cr.Category); cat != nil {
				weight = fmt.Sprintf("%.1f", cat.Weight)
				if cat.Required {
					required = "✅"
				} else {
					required = "❌"
				}
			}
		}

		scoreStr := formatScore(cr)
		b.WriteString(fmt.Sprintf("| **%s** | %s | %s | %s | %s |\n",
			cr.Category,
			scoreStr,
			weight,
			required,
			truncate(cr.Reasoning, 50)))
	}
	b.WriteString("\n---\n\n")

	// Evidence section
	hasEvidence := false
	for _, cr := range report.Categories {
		if len(cr.Evidence) > 0 {
			hasEvidence = true
			break
		}
	}

	if hasEvidence {
		b.WriteString("### Evidence\n\n")
		for _, cr := range report.Categories {
			if len(cr.Evidence) > 0 {
				b.WriteString(fmt.Sprintf("**%s:**\n", cr.Category))
				for _, ev := range cr.Evidence {
					b.WriteString(fmt.Sprintf("- `%s`\n", ev))
				}
				b.WriteString("\n")
			}
		}
		b.WriteString("---\n\n")
	}

	// Findings section
	if len(report.Findings) > 0 {
		b.WriteString("### Findings\n\n")

		for _, sev := range rubric.AllSeverities() {
			findings := filterBySeverity(report.Findings, sev)
			if len(findings) == 0 {
				continue
			}

			b.WriteString(fmt.Sprintf("#### %s %s (%d)\n\n",
				severityIcon(sev),
				strings.Title(string(sev)),
				len(findings)))

			for _, f := range findings {
				b.WriteString(fmt.Sprintf("**%s** [%s]\n", f.Title, f.Category))
				b.WriteString(fmt.Sprintf("- %s\n", f.Description))
				if f.Recommendation != "" {
					b.WriteString(fmt.Sprintf("- **Recommendation**: %s\n", f.Recommendation))
				}
				b.WriteString("\n")
			}
		}
		b.WriteString("---\n\n")
	} else {
		b.WriteString("### Findings\n\n")
		b.WriteString("**None** - No issues identified.\n\n")
		b.WriteString("---\n\n")
	}

	// Next Steps
	writeNextSteps(&b, report)

	// Footer
	b.WriteString("---\n\n")
	b.WriteString("*Generated by structured-evaluation*\n")

	_, err := fmt.Fprint(r.w, b.String())
	return err
}

// Helper functions

func writeNextSteps(b *strings.Builder, report *rubric.Rubric) {
	if len(report.NextSteps.Immediate) == 0 && len(report.NextSteps.Recommended) == 0 {
		return
	}

	b.WriteString("### Next Steps\n\n")

	if len(report.NextSteps.Immediate) > 0 {
		b.WriteString("**Immediate Actions:**\n\n")
		for _, action := range report.NextSteps.Immediate {
			b.WriteString(fmt.Sprintf("- [ ] %s", action.Action))
			if action.Category != "" {
				b.WriteString(fmt.Sprintf(" [%s]", action.Category))
			}
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}

	if len(report.NextSteps.Recommended) > 0 {
		b.WriteString("**Recommended:**\n\n")
		for _, action := range report.NextSteps.Recommended {
			b.WriteString(fmt.Sprintf("- [ ] %s", action.Action))
			if action.Category != "" {
				b.WriteString(fmt.Sprintf(" [%s]", action.Category))
			}
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}

	if report.NextSteps.RerunCommand != "" {
		b.WriteString(fmt.Sprintf("**Re-run command**: `%s`\n\n", report.NextSteps.RerunCommand))
	}
}

func decisionIcon(status rubric.DecisionStatus) string {
	switch status {
	case rubric.DecisionPass:
		return "✅"
	case rubric.DecisionConditional:
		return "⚠️"
	case rubric.DecisionFail:
		return "❌"
	case rubric.DecisionHumanReview:
		return "👤"
	default:
		return "📋"
	}
}

func scoreIcon(score rubric.ScoreValue) string {
	switch score {
	case rubric.ScorePass:
		return "🟢"
	case rubric.ScorePartial:
		return "🟡"
	case rubric.ScoreFail:
		return "🔴"
	default:
		return "⚪"
	}
}

func severityIcon(sev rubric.Severity) string {
	switch sev {
	case rubric.SeverityCritical:
		return "🔴"
	case rubric.SeverityHigh:
		return "🔴"
	case rubric.SeverityMedium:
		return "🟡"
	case rubric.SeverityLow:
		return "🟢"
	case rubric.SeverityInfo:
		return "ℹ️"
	default:
		return "⚪"
	}
}

func filterBySeverity(findings []rubric.Finding, sev rubric.Severity) []rubric.Finding {
	var result []rubric.Finding
	for _, f := range findings {
		if f.Severity == sev {
			result = append(result, f)
		}
	}
	return result
}

func truncate(s string, maxLen int) string {
	if len(s) <= maxLen {
		return s
	}
	return s[:maxLen-3] + "..."
}

// formatScore formats a category score, preferring numeric score when available.
// Returns "5/5 🟢" format for numeric scores, "🟢 Pass" for categorical only.
func formatScore(cr rubric.CategoryResult) string {
	if cr.NumericScore != nil {
		score := int(*cr.NumericScore)
		icon := numericScoreIcon(score)
		return fmt.Sprintf("%d/5 %s", score, icon)
	}
	// Fall back to categorical
	icon := scoreIcon(cr.Score)
	return fmt.Sprintf("%s %s", icon, strings.Title(string(cr.Score)))
}

// numericScoreIcon returns an icon based on 5-point scale.
// 5 = green, 3-4 = yellow, 1-2 = red
func numericScoreIcon(score int) string {
	switch {
	case score >= 5:
		return "🟢"
	case score >= 3:
		return "🟡"
	default:
		return "🔴"
	}
}
